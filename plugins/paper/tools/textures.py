# Makes the plugin's textures from the source scans (PNG, in textures/src/, not committed):
#
#   crumpled-white.png, crumpled-heavy.png -> crease-light.jpg, crease-heavy.jpg: grey, the median lifted to white, so
#       multiplying one over the paper adds only the creases' shade and never greys the sheet
#   smooth-white.png -> smooth-white.jpg: grey, median lifted to white like the crease maps (a grain for white paper)
#   newsprint.png, kraft.png -> the same name as .jpg, unchanged: the paper itself, colour and all
#   scrap-white.png, scrap-kraft.png, binder.png, cardboard.png -> the same name as .jpg, square, unchanged: the papers
#       behind <Scrapline> (from templates/scrapline), and binder and cardboard as cut-out stocks too
#   torn-edge.png -> copied (it has alpha)
#   textures/index.ts: the nine JPEGs as data: URLs. A plugin's own files have no stable path once the project is
#       bundled, and `new Image()` takes a data: URL, so the scans travel inside the code.
#
#   python3 -I plugins/paper/tools/textures.py

import base64
import os
import shutil
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'textures', 'src')
OUT = os.path.join(HERE, '..', 'textures')


def median(im):
    h = im.histogram()
    total, run = sum(h), 0
    for v, n in enumerate(h):
        run += n
        if run > total / 2:
            return v
    return 255


for name, out in [('crumpled-white', 'crease-light'), ('crumpled-heavy', 'crease-heavy'), ('smooth-white', 'smooth-white')]:
    grey = Image.open(os.path.join(SRC, name + '.png')).convert('L')
    m = median(grey)
    grey = grey.point(lambda v: min(255, round(v * 255 / m)))
    grey.resize((1024, round(1024 * grey.height / grey.width)), Image.LANCZOS).save(os.path.join(OUT, out + '.jpg'), quality=88)

for name in ['newsprint', 'kraft']:
    im = Image.open(os.path.join(SRC, name + '.png')).convert('RGB')
    im.resize((1024, round(1024 * im.height / im.width)), Image.LANCZOS).save(os.path.join(OUT, name + '.jpg'), quality=88)

for name in ['scrap-white', 'scrap-kraft', 'binder', 'cardboard']:
    im = Image.open(os.path.join(SRC, name + '.png')).convert('RGB')
    im.resize((1024, 1024), Image.LANCZOS).save(os.path.join(OUT, name + '.jpg'), quality=85)

shutil.copy(os.path.join(SRC, 'torn-edge.png'), os.path.join(OUT, 'torn-edge.png'))

names = {'creaseLight': 'crease-light', 'creaseHeavy': 'crease-heavy', 'smoothWhite': 'smooth-white', 'newsprint': 'newsprint', 'kraft': 'kraft',
         'scrapWhite': 'scrap-white', 'scrapKraft': 'scrap-kraft', 'binder': 'binder', 'cardboard': 'cardboard'}
with open(os.path.join(OUT, 'index.ts'), 'w') as f:
    f.write('// Generated by tools/textures.py from textures/*.jpg: do not edit.\n')
    f.write('export const TEXTURE_DATA = {\n')
    for key, name in names.items():
        data = base64.b64encode(open(os.path.join(OUT, name + '.jpg'), 'rb').read()).decode()
        f.write(f"  {key}: 'data:image/jpeg;base64,{data}',\n")
    f.write('};\n')
