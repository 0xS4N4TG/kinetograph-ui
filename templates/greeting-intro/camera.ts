const channel = (i: number): [number, number][] => KEYS.map((k) => [k[0], k[i]]);
const CH = [1, 2, 3, 4, 5, 6].map(channel);

export interface Cam {
  x: number;
  y: number;
  s: number;
  a: number;
  b: number;
  c: number;
  opacity: number;
  perspective: number;
}

/** The camera at frame f of the 60 fps reference. */
export const camera = (f: number): Cam => {
  const [x, y, ls, a, b, c] = CH.map((ch) => spline(f, ch));
  // The window fades in while it grows in at the lower right.
  const opacity = ramp(f, [[8, 0], [10, 0.26], [12, 0.52], [14, 0.8], [16, 1]], (t) => t);
  return { x, y, s: Math.exp(ls), a, b, c, opacity, perspective: PERSPECTIVE };
};
